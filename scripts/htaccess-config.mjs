// Writes public/.htaccess for the cPanel (Apache/LiteSpeed) host: the same security headers and cache times as
// vercel.json, clean URLs (/careers serves careers.html), HTTPS and no-www, and /api/<name> routed to PHP.
import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import { buildSecurityHeaders, inlineScriptHashes, inlineStyleHashes } from "../server/app.mjs";

const root = new URL("../", import.meta.url);

export async function buildHtaccess() {
  const html = await readFile(new URL("public/index.html", root), "utf8");
  const headers = Object.entries(buildSecurityHeaders(inlineScriptHashes(html), inlineStyleHashes(html)))
    .map(([k, v]) => `  Header always set ${k} "${v.replace(/"/g, '\\"')}"`).join("\n");
  return `# Generated by scripts/htaccess-config.mjs (npm run build); edit that script, not this file.
Options -Indexes -MultiViews
DirectoryIndex index.html index.php
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /

  # one address: https, no www
  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP:X-Forwarded-Proto} !=https
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
  RewriteCond %{HTTP_HOST} ^www\\.(.+)$ [NC]
  RewriteRule ^ https://%1%{REQUEST_URI} [L,R=301]

  # server code and settings are never served
  RewriteRule ^api/_lib/ - [F,L]

  # /api/<name> runs api/<name>.php
  RewriteRule ^api/([a-z-]+)/?$ api/$1.php [L,QSA]

  # clean URLs: /careers.html redirects to /careers, and /careers serves careers.html
  RewriteRule ^index\\.html$ / [R=301,L]
  RewriteCond %{THE_REQUEST} \\s/+([^.?\\s]+)\\.html[\\s?] [NC]
  RewriteRule ^ /%1 [R=301,L]
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteCond %{DOCUMENT_ROOT}/$1.html -f
  RewriteRule ^(.+?)/?$ $1.html [L]
</IfModule>

<IfModule mod_mime.c>
  AddType image/webp .webp
  AddType font/woff2 .woff2
  AddType application/manifest+json .webmanifest
</IfModule>

<IfModule mod_headers.c>
${headers}
  # file names are not content-hashed: code revalidates, pictures are cached for a month, fonts for a year
  <FilesMatch "\\.(woff2?)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(webp|avif|png|jpe?g|svg|ico)$">
    Header set Cache-Control "public, max-age=2592000, stale-while-revalidate=86400"
  </FilesMatch>
  <FilesMatch "\\.(css|js|html)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml
</IfModule>
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile(new URL("public/.htaccess", root), await buildHtaccess());
  console.log("wrote public/.htaccess");
}
